    /// Regression for issue #84 Bug 3: keyboard speed control was overwritten by the
    /// next signal poll, making SpeedUp/SlowDown dead keys in `--system`/`--audio` mode.
    #[test]
    fn test_keyboard_buoyancy_survives_signal_poll() {
        let mut sim = Simulation::new(PhysicsParams::default(), 6, 42);
        for _ in 0..10 {
            sim.nudge_buoyancy(0.1);
        }
        let after_keys = sim.params.buoyancy;

        sim.apply_signals(&SystemSignals::new(0.0, 0.0, 0.5, 0.0));
        let after_poll = sim.params.buoyancy;

        assert_eq!(
            after_poll, after_keys,
            "signal polling must not discard the user's accumulated buoyancy offset"
        );

        // Repeated polls must stay stable, not compound or drift.
        sim.apply_signals(&SystemSignals::new(0.0, 0.0, 0.5, 0.0));
        assert_eq!(sim.params.buoyancy, after_keys);

        // And lowering must still work, bounded by the configured range.
        sim.nudge_buoyancy(-100.0);
        assert_eq!(sim.params.buoyancy, Simulation::MIN_CONFIG_BUOYANCY);
    }

