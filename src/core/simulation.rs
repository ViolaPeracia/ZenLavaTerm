    #[test]
    fn test_compact_scaling_is_idempotent_and_preserves_base_params() {
        let profile = crate::widget::CompactProfile {
            blob_count: 6,
            radius_scale: 0.85,
            buoyancy_scale: 1.25,
            noise_scale: 0.90,
        };
        let mut sim = Simulation::new(PhysicsParams::default(), 12, 42);
        crate::widget::CompactScaler::adapt_simulation(&profile, &mut sim);
        // Calling twice must never compound
        crate::widget::CompactScaler::adapt_simulation(&profile, &mut sim);

        assert_eq!(sim.blobs.len(), 6);
        assert_eq!(sim.base_params().buoyancy, 0.80);
        assert!((sim.params.buoyancy - 0.80 * 1.25).abs() < 1e-5);
        assert!((sim.params.noise - 0.15 * 0.90).abs() < 1e-5);

        // Reactive poll scales on top of compact scales
        sim.apply_signals(&SystemSignals::new(0.0, 0.0, 1.0, 0.0));
        assert!((sim.params.buoyancy - 0.80 * 1.25 * 1.375).abs() < 1e-4);

        // Growing back to large viewport restores full blob count and 1.0 scales without losing existing blobs
        let first_blob_pos = (sim.blobs[0].x, sim.blobs[0].y);
        sim.apply_compact_scales(12, 1.0, 1.0, 1.0);
        assert_eq!(sim.blobs.len(), 12);
        assert_eq!((sim.blobs[0].x, sim.blobs[0].y), first_blob_pos);
        assert!((sim.params.buoyancy - 0.80 * 1.375).abs() < 1e-4);

        // Reset preserves compact scales while clearing user offset
        sim.apply_compact_scales(4, 0.65, 1.25, 0.80);
        sim.nudge_buoyancy(0.5);
        sim.reset(42);
        assert_eq!(sim.blobs.len(), 4);
        assert_eq!(sim.radius_scale, 0.65);
        assert!((sim.params.buoyancy - 0.80 * 1.25).abs() < 1e-5);
    }

