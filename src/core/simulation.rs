//! Simulation orchestrator managing blob states, physics stepping, and scalar field evaluation.

use super::field::{evaluate_field, evaluate_with_temperature, ScalarField};
use super::metaball::Blob;
use super::physics::{step_blob, PhysicsParams};

/// Minimal fast XorShift64 PRNG for deterministic noise without external dependencies.
#[derive(Debug, Clone)]
struct SimplePrng {
    state: u64,
}

impl SimplePrng {
    fn new(seed: u64) -> Self {
        Self {
            state: if seed == 0 {
                0x5465_726d_4c61_7661
            } else {
                seed
            },
        }
    }

    fn next_u32(&mut self) -> u32 {
        let mut x = self.state;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.state = x;
        x as u32
    }

    /// Returns a float in $[-1.0, 1.0]$.
    fn next_f32_signed(&mut self) -> f32 {
        let val = (self.next_u32() & 0xFFFF) as f32 / 65535.0;
        val * 2.0 - 1.0
    }
}

/// The central LavaTerm simulation container.
#[derive(Debug, Clone)]
pub struct Simulation {
    /// Active metaballs.
    pub blobs: Vec<Blob>,
    /// Physics parameters.
    ///
    /// Derived state: `noise` and `buoyancy` are recomputed from `base_params`,
    /// the reactive multipliers, and the user offset on every
    /// [`apply_signals`](Self::apply_signals) /
    /// [`apply_audio_signals`](Self::apply_audio_signals) call. Writing them
    /// directly does not survive the next poll — use
    /// [`nudge_buoyancy`](Self::nudge_buoyancy) for user input. The remaining
    /// fields are never modulated and are safe to read.
    pub params: PhysicsParams,
    /// Scalar field evaluator.
    pub field: ScalarField,
    /// Total elapsed simulation time in seconds.
    pub elapsed_time: f32,
    /// Base radius scale for compact / adaptive viewports.
    pub radius_scale: f32,
    /// Physics parameters as configured by the user. Reactive modulation is computed
    /// relative to these so `[simulation]` values in `config.toml` are never discarded.
    base_params: PhysicsParams,
    /// Blob radii as generated by [`Simulation::new`], before any radius scaling.
    /// Radius modulation is relative to these, preserving per-blob random variety.
    base_radii: Vec<f32>,
    /// Accumulated user buoyancy offset from keyboard and scroll interactions.
    user_buoyancy_offset: f32,
    /// Buoyancy multiplier derived from the active reactive source (1.0 = no modulation).
    reactive_buoyancy_scale: f32,
    /// Noise multiplier derived from the active reactive source (1.0 = no modulation).
    reactive_noise_scale: f32,
    /// Radius multiplier derived from the active reactive source (1.0 = no modulation).
    radius_multiplier: f32,
    /// Internal deterministic PRNG.
    prng: SimplePrng,
}

impl Simulation {
    /// Maximum allowable delta time to avoid simulation instability.
    pub const MAX_DT: f32 = 0.10;

    /// Lowest buoyancy `Config::validate` accepts from `[simulation].buoyancy`.
    /// Clamping a freshly constructed simulation to this range would silently rewrite
    /// a valid configuration, so construction must not clamp at all.
    const MIN_CONFIG_BUOYANCY: f32 = 0.0;
    /// Highest buoyancy `Config::validate` accepts from `[simulation].buoyancy`.
    const MAX_CONFIG_BUOYANCY: f32 = 5.0;

    /// Creates a new simulation with `blob_count` blobs arranged with initial thermal distribution.
    pub fn new(params: PhysicsParams, blob_count: usize, seed: u64) -> Self {
        let mut prng = SimplePrng::new(seed);
        let mut blobs = Vec::with_capacity(blob_count);

        let count = blob_count.max(1);
        for i in 0..count {
            let frac = (i as f32 + 0.5) / count as f32;
            let x = 0.15 + 0.70 * frac;
            // Half start near bottom, half start near top with alternating temperatures
            let is_bottom = i % 2 == 0;
            let y = if is_bottom {
                0.10 + 0.10 * prng.next_f32_signed()
            } else {
                0.85 + 0.10 * prng.next_f32_signed()
            };
            let temp = if is_bottom { 0.90 } else { 0.10 };
            let radius = 0.08 + 0.04 * (prng.next_f32_signed().abs());

            let mut blob = Blob::new(x, y, radius, temp);
            blob.vx = prng.next_f32_signed() * 0.05;
            blob.vy = prng.next_f32_signed() * 0.05;
            blobs.push(blob);
        }

        let base_radii = blobs.iter().map(|b| b.radius).collect();
        let mut sim = Self {
            blobs,
            base_params: params,
            params,
            field: ScalarField,
            elapsed_time: 0.0,
            radius_scale: 1.0,
            base_radii,
            user_buoyancy_offset: 0.0,
            reactive_buoyancy_scale: 1.0,
            reactive_noise_scale: 1.0,
            radius_multiplier: 1.0,
            prng,
        };
        sim.sync_derived_params();
        sim
    }

    /// Returns the user-configured physics parameters, before reactive modulation.
    pub fn base_params(&self) -> PhysicsParams {
        self.base_params
    }

    /// Recomputes `self.params` from `base_params`, the reactive multipliers, and the
    /// accumulated user buoyancy offset. Idempotent: calling it repeatedly never
    /// compounds, so keyboard input survives signal polling.
    ///
    /// The result is *not* clamped. A valid `[simulation].buoyancy` of `5.0` must stay
    /// `5.0`; clamping here would silently rewrite configuration that `Config::validate`
    /// already accepted. Runaway is prevented instead by bounding the user offset in
    /// [`Self::nudge_buoyancy`].
    fn sync_derived_params(&mut self) {
        self.params.noise = self.base_params.noise * self.reactive_noise_scale;
        self.params.buoyancy =
            self.base_params.buoyancy * self.reactive_buoyancy_scale + self.user_buoyancy_offset;
    }

    /// Applies a user-requested buoyancy change (keyboard speed control, scroll pressure).
    ///
    /// The change is stored as an offset on top of the configured base value, so reactive
    /// modulation can no longer silently discard it.
    ///
    /// The offset is bounded to the range that can still change the result. Without that,
    /// holding a speed key would bank credit that later `SlowDown` presses must first
    /// exhaust, making the control feel unresponsive in both directions.
    pub fn nudge_buoyancy(&mut self, delta: f32) {
        // Only the headroom relative to the current reactive value can change the
        // result, so the offset is bounded by exactly that. This keeps a held speed key
        // from banking credit that later SlowDown presses must first exhaust, without
        // constraining the configured baseline itself.
        let signal_term = self.base_params.buoyancy * self.reactive_buoyancy_scale;
        let max_offset = Self::MAX_CONFIG_BUOYANCY - signal_term;
        let min_offset = Self::MIN_CONFIG_BUOYANCY - signal_term;

        self.user_buoyancy_offset =
            (self.user_buoyancy_offset + delta).clamp(min_offset.min(0.0), max_offset.max(0.0));
        self.sync_derived_params();
    }

    /// Replaces the configured physics baseline, discarding any accumulated user offset.
    ///
    /// Used by [`crate::widget::CompactScaler::adapt_simulation`] so that compact
    /// physics scaling becomes the new baseline instead of being overwritten by the next
    /// reactive poll.
    pub fn set_base_params(&mut self, params: PhysicsParams) {
        self.base_params = params;
        self.user_buoyancy_offset = 0.0;
        self.sync_derived_params();
    }

    /// Sets the reactive radius multiplier and recomputes blob radii.
    fn set_radius_multiplier(&mut self, radius_multiplier: f32) {
        self.radius_multiplier = radius_multiplier;
        self.sync_derived_radii();
    }

    /// Recomputes every blob radius from `base_radii`, `radius_scale`, and the reactive
    /// `radius_multiplier`. Idempotent, and preserves the per-blob variety generated by
    /// [`Simulation::new`].
    fn sync_derived_radii(&mut self) {
        debug_assert_eq!(
            self.blobs.len(),
            self.base_radii.len(),
            "blobs and base_radii must stay the same length; blobs is pub so external \
             code must not add or remove metaballs after Simulation::new"
        );
        for (blob, &base) in self.blobs.iter_mut().zip(self.base_radii.iter()) {
            blob.radius = (base * self.radius_scale * self.radius_multiplier).max(0.01);
        }
    }

    /// Scales all blob radii by `scale` and sets `self.radius_scale`.
    ///
    /// Idempotent: radii are recomputed from their generated base values rather than
    /// multiplied in place, so repeated calls with the same scale do not compound.
    pub fn apply_radius_scale(&mut self, scale: f32) {
        self.radius_scale = scale;
        self.sync_derived_radii();
    }

    /// Advances the simulation by $\Delta t$ seconds.
    pub fn step(&mut self, dt: f32) {
        let dt_effective = dt.clamp(0.0, Self::MAX_DT);
        self.elapsed_time += dt_effective;

        for blob in &mut self.blobs {
            let noise_x = self.prng.next_f32_signed();
            let noise_y = self.prng.next_f32_signed();
            step_blob(blob, &self.params, dt_effective, (noise_x, noise_y));
        }
    }

    /// Evaluates the scalar field at coordinate `(px, py)` in $[0.0, 1.0] \times [0.0, 1.0]$.
    #[inline]
    pub fn evaluate_field(&self, px: f32, py: f32) -> f32 {
        evaluate_field(&self.blobs, px, py)
    }

    /// Evaluates field intensity and temperature at `(px, py)`.
    #[inline]
    pub fn evaluate_at(&self, px: f32, py: f32) -> (f32, f32) {
        evaluate_with_temperature(&self.blobs, px, py)
    }

    /// Dynamically modulates physics constants and blob parameters from normalized reactive signals.
    ///
    /// Modulation is applied as a multiplier on the user-configured `base_params`, so
    /// `[simulation]` values from `config.toml` remain the reference point and a setting
    /// of `noise = 0.0` is respected. Idempotent — safe to call every poll.
    pub fn apply_signals(&mut self, signals: &crate::reactive::SystemSignals) {
        // CPU load modulates Brownian thermal noise and turbulence (base * (1.0 + cpu * 2.5))
        self.reactive_noise_scale = 1.0 + signals.cpu_load * 2.5;

        // Battery level modulates convection: low battery -> sluggish lava, high -> lively.
        // Relative to the configured buoyancy so `[simulation].buoyancy` stays meaningful.
        self.reactive_buoyancy_scale = 0.625 + signals.battery_level * 0.75;

        // RAM memory usage modulates blob size: higher memory -> larger, expanding blobs.
        // Applied per-blob on top of each blob's own generated radius, preserving variety.
        self.set_radius_multiplier(0.85 + signals.memory_usage * 0.40);

        self.sync_derived_params();
    }

    /// Advances the simulation by $\Delta t$ seconds while applying reactive system signals.
    pub fn step_reactive(&mut self, dt: f32, signals: &crate::reactive::SystemSignals) {
        self.apply_signals(signals);
        self.step(dt);
    }

    /// Dynamically modulates physics constants and blob kinetics from normalized audio spectrum signals.
    ///
    /// Like [`Simulation::apply_signals`], modulation is a multiplier on the configured
    /// base values and is idempotent, so keyboard speed control survives audio polling.
    pub fn apply_audio_signals(&mut self, audio: &crate::audio::AudioSignals) {
        // Bass kick gives strong convective thrust and upward buoyancy surge
        self.reactive_buoyancy_scale = 1.0 + audio.bass * 1.875;

        // Midrange frequencies modulate fluid turbulence and Brownian noise
        self.reactive_noise_scale = 1.0 + audio.mid * 2.5;

        // Audio does not modulate radius. Reset it so that radii fall back to the
        // configured base rather than retaining a system-signal multiplier.
        self.set_radius_multiplier(1.0);

        self.sync_derived_params();

        // Treble adds subtle kinetic energy jitter
        if audio.treble > 0.3 {
            for blob in &mut self.blobs {
                blob.vx += (self.prng.next_f32_signed()) * audio.treble * 0.02;
            }
        }
    }

    /// Advances the simulation by $\Delta t$ seconds while applying reactive audio signals.
    pub fn step_audio(&mut self, dt: f32, audio: &crate::audio::AudioSignals) {
        self.apply_audio_signals(audio);
        self.step(dt);
    }

    /// Applies a user interaction impulse to the simulation.
    pub fn apply_interaction(&mut self, interaction: &super::interaction::Interaction) {
        match *interaction {
            super::interaction::Interaction::Shockwave { x, y, force } => {
                super::interaction::apply_shockwave(&mut self.blobs, x, y, force);
            }
            super::interaction::Interaction::Stir {
                x,
                y,
                vx,
                vy,
                radius,
            } => {
                super::interaction::apply_stir(&mut self.blobs, x, y, vx, vy, radius);
            }
            super::interaction::Interaction::Ripple { intensity } => {
                let prng = &mut self.prng;
                super::interaction::apply_ripple(&mut self.blobs, intensity, || {
                    prng.next_f32_signed()
                });
            }
            super::interaction::Interaction::Pressure { delta } => {
                self.nudge_buoyancy(delta * 0.15);
            }
            super::interaction::Interaction::ThermalPulse {
                x,
                y,
                temperature_delta,
                radius,
            } => {
                super::interaction::apply_thermal_pulse(
                    &mut self.blobs,
                    x,
                    y,
                    temperature_delta,
                    radius,
                );
            }
        }
    }
}

