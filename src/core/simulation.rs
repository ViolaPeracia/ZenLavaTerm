    /// Regression for review finding P2: the offset used to keep accumulating after the
    /// effective value had saturated, so later `SlowDown` presses did nothing visible
    /// until the banked credit was spent.
    #[test]
    fn test_buoyancy_offset_does_not_bank_credit() {
        let mut sim = Simulation::new(PhysicsParams::default(), 6, 42);
        sim.apply_signals(&SystemSignals::new(0.0, 0.0, 0.0, 0.0));

        for _ in 0..1_000 {
            sim.nudge_buoyancy(0.1);
        }
        let saturated = sim.params.buoyancy;
        assert_eq!(saturated, Simulation::MAX_CONFIG_BUOYANCY);

        // The very first SlowDown must have a visible effect.
        sim.nudge_buoyancy(-0.1);
        assert!(
            sim.params.buoyancy < saturated,
            "first SlowDown after saturation must be visible: {} vs {saturated}",
            sim.params.buoyancy
        );

        // And the offset must stay within the range that can still change the result.
        for _ in 0..1_000 {
            sim.nudge_buoyancy(0.1);
        }
        assert!(
            sim.params.buoyancy <= Simulation::MAX_CONFIG_BUOYANCY,
            "sustained SpeedUp must not push buoyancy past the configured maximum"
        );

        for _ in 0..1_000 {
            sim.nudge_buoyancy(-0.1);
        }
        assert_eq!(sim.params.buoyancy, Simulation::MIN_CONFIG_BUOYANCY);
    }

    /// Regression for review finding P3: `CompactScaler::adapt_simulation` wrote
    /// `sim.params` directly, so the next reactive poll rebuilt from the un-compacted
    /// baseline and silently dropped the compact physics scaling.
    #[test]
    fn test_set_base_params_makes_compact_scaling_durable() {
        let profile = crate::widget::CompactProfile {
            blob_count: 6,
            radius_scale: 0.85,
            buoyancy_scale: 1.25,
            noise_scale: 0.90,
        };
        let mut sim = Simulation::new(PhysicsParams::default(), 6, 42);
        crate::widget::CompactScaler::adapt_simulation(&profile, &mut sim);

        assert_eq!(sim.base_params().buoyancy, 0.80 * 1.25);
        assert_eq!(sim.base_params().noise, 0.15 * 0.90);

        // A reactive poll must scale around the compact baseline, not erase it.
        // battery = 1.0 -> buoyancy scale = 0.625 + 1.0 * 0.75 = 1.375
        // cpu    = 0.0 -> noise scale    = 1.0
        sim.apply_signals(&SystemSignals::new(0.0, 0.0, 1.0, 0.0));
        assert!(
            (sim.params.buoyancy - 0.80 * 1.25 * 1.375).abs() < 1e-4,
            "compact buoyancy baseline lost after poll: {}",
            sim.params.buoyancy
        );
        assert!(
            (sim.params.noise - 0.15 * 0.90).abs() < 1e-4,
            "compact noise baseline lost after poll: {}",
            sim.params.noise
        );

        // A user nudge must also preserve the compact baseline.
        sim.nudge_buoyancy(0.1);
        assert_eq!(sim.base_params().buoyancy, 0.80 * 1.25);
    }

    /// Audio does not drive radius, so it must clear any system-signal radius multiplier
    /// rather than leaving a stale one behind.
    #[test]
    fn test_audio_signals_reset_radius_multiplier() {
        let mut sim = Simulation::new(PhysicsParams::default(), 6, 42);
        let generated = sim.blobs.iter().map(|b| b.radius).collect::<Vec<_>>();

        sim.apply_signals(&SystemSignals::new(0.0, 1.0, 0.0, 0.0));
        let system_scaled = sim.blobs.iter().map(|b| b.radius).collect::<Vec<_>>();

        // Audio does not drive radius, so every blob must fall back to its own
        // generated radius rather than keeping the system multiplier.
        sim.apply_audio_signals(&AudioSignals::new(0.0, 0.0, 0.0, 0.0));
        let audio_scaled = sim.blobs.iter().map(|b| b.radius).collect::<Vec<_>>();

        for i in 0..sim.blobs.len() {
            let before = system_scaled[i];
            let after = audio_scaled[i];
            let base = generated[i];
            assert!(
                after < before,
                "blob {i} kept the system radius multiplier: {after} vs {before}"
            );
            assert!(
                (after - base).abs() < 1e-6,
                "blob {i} must return to its generated radius: {after} vs {base}"
            );
        }

        // and audio mode must be stable across repeated polls
        sim.apply_audio_signals(&AudioSignals::new(0.0, 0.0, 0.0, 0.0));
        let audio_again = sim.blobs.iter().map(|b| b.radius).collect::<Vec<_>>();
        assert_eq!(audio_scaled, audio_again);
    }

    /// `apply_radius_scale` must compose with reactive radius modulation, not reset it.
    #[test]
    fn test_radius_scale_composes_with_signal_modulation() {
        let mut sim = Simulation::new(PhysicsParams::default(), 8, 99);
        let generated: Vec<f32> = sim.blobs.iter().map(|b| b.radius).collect();

        // radius = generated * radius_scale * radius_multiplier
        // memory_usage = 1.0 -> multiplier = 0.85 + 0.40 = 1.25
        let radius_scale = 0.85;
        let radius_multiplier = 1.25;
        sim.apply_radius_scale(radius_scale);
        sim.apply_signals(&SystemSignals::new(0.0, 1.0, 0.0, 0.0));

        for (blob, &base) in sim.blobs.iter().zip(generated.iter()) {
            let expected = (base * radius_scale * radius_multiplier).max(0.01);
            assert!(
                (blob.radius - expected).abs() < 1e-6,
                "radius must be the product of both scales: {} vs expected {}",
                blob.radius,
                expected
            );
        }

        // Rescaling after a poll must be reflected, and must survive the next poll
        // rather than being reset from `generated`.
        sim.apply_radius_scale(0.5);
        let after_rescale = sim.blobs[0].radius;
        sim.apply_signals(&SystemSignals::new(0.0, 1.0, 0.0, 0.0));
        assert!(
            (sim.blobs[0].radius - after_rescale).abs() < 1e-6,
            "rescaled radius must survive the next poll: {} vs {}",
            sim.blobs[0].radius,
            after_rescale
        );
    }
